import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { payoutExampleRows } from '../js/streakPayouts.mjs';

export function generatePayoutExamples() {
  return `# StreakBet payout examples (simulation)

Generated by \`npm run docs:streak-payouts\`. Do not edit the table manually.
Source: [StreakBetEscrow.sol](../contracts/StreakBetEscrow.sol),
\`_assignStreakPlaces\` and \`_distributeStreakPayouts\`.
The generator is checked against actual local-contract transfers by Hardhat tests.

Each entrant stakes **100 example BNUT** (18 decimals). No yield, fees, swaps,
or USD conversion. This stake is illustrative, not the captain's chosen stake.
All non-completers in these scenarios explicitly forfeit. Actual unsuccessful
entrants also receive no settlement payout. Rank order is assumed, not predicted.
Every number is exact; tiny treasury amounts are integer-rounding dust.

| Entrants | Completed | Forfeits | Payouts in rank order (BNUT) | Treasury (BNUT) |
| --- | --- | --- | --- | --- |
${payoutExampleRows().map(row => `| ${row.join(' | ')} |`).join('\n')}

Principal refunds: full stake except third place, which starts with half
(rounded down in base units). The rest of the pot is the bonus pool, including
forfeits **and the withheld half of third place's principal**, even with no
forfeits. Bonus weights are 3:2:1 for first/second/third and 1 for **each**
additional finisher; only present finishers contribute to the denominator.
Each bonus rounds down independently. Dust goes to the configured treasury;
with zero finishers the entire pot goes there. Cancellation is a separate
owner action that refunds stakes, not this settlement calculation.

See [the journey and policy boundaries](STREAKBET_JOURNEY.md) before joining.
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../docs/STREAKBET_PAYOUT_EXAMPLES.md', import.meta.url), generatePayoutExamples());
}
