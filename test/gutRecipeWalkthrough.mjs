import assert from 'node:assert/strict';

export async function gutRecipeWalkthrough(page, shot = async () => {}) {
  const original = await page.evaluate(() => localStorage.getItem('fitnessTrackerData'));
  const form = page.locator('#gut-recipe-form'), period = page.locator('#gut-observation-form');
  await page.locator('#gut-health-open').click();
  await page.locator('#gut-smoothie-starter').click();
  assert.equal(await form.locator('[name=recipeName]').inputValue(), 'Gut Vitality Yogurt Smoothie');
  assert.equal(await page.locator('.gut-recipe-ingredient').count(), 7);
  assert.equal(await page.locator('.gut-recipe-ingredient').nth(1).locator('[data-field=amount]').inputValue(), '');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('fitnessTrackerData')).foods.length), JSON.parse(original).foods.length);
  await form.locator('[name=mode]').selectOption('estimate');
  await form.locator('details').last().locator('summary').click();
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#gut-smoothie-estimates').click();
  assert.equal(await page.locator('#gut-recipe-estimates [data-nutrient=calories]').inputValue(), '');
  assert.equal(await page.locator('#gut-recipe-estimates [data-nutrient=calcium]').inputValue(), '390');
  await page.locator('#gut-recipe-estimates [data-nutrient=calories]').fill('400');
  await page.locator('#gut-recipe-estimates [data-nutrient=protein]').fill('30');
  await page.locator('#gut-recipe-estimates [data-nutrient=zinc]').fill('0');
  await page.locator('#gut-recipe-estimates [data-nutrient=copper]').fill('0.009');
  await form.locator('button[type=submit]').click();
  assert.match(await page.locator('#gut-recipe-status').innerText(), /saved, not logged/);
  const get = () => page.evaluate(() => JSON.parse(localStorage.getItem('fitnessTrackerData')));
  const saved = await get();
  assert.equal(saved.mealRecipes.length, 1);
  assert.equal(saved.foods.length, JSON.parse(original).foods.length);
  await period.locator('[name=periodName]').fill('Synthetic smoothie observations');
  await period.locator('[name=recipeId]').selectOption(saved.mealRecipes[0].id);
  await period.locator('[name=start]').fill('2026-10-28');
  await page.locator('#gut-period-fourteen').click();
  assert.equal(await period.locator('[name=end]').inputValue(), '2026-11-10');
  await period.locator('[name=fastStart]').fill('2026-10-27T18:00');
  await period.locator('[name=fastEnd]').fill('2026-10-28T08:00');
  await period.locator('button[type=submit]').click();
  assert.match(await page.locator('#gut-recipe-status').innerText(), /Observation period saved/);
  await page.locator('#gut-observation-list > details > summary').click();
  assert.equal(await page.locator('#gut-observation-list > details > ul > li').count(), 14);
  assert.match(await page.locator('#gut-observation-list').innerText(), /14 hours recorded/);
  assert.match(await page.locator('#gut-observation-list').innerText(), /No observations logged/);
  await page.locator('#gut-recipe-list button').filter({ hasText: 'Review & log portion' }).click();
  assert.equal(await page.locator('#dietNutrCalories').inputValue(), '400');
  assert.equal(await page.locator('#dietNutrProtein').inputValue(), '30');
  assert.equal(await page.locator('#dietNutrIodine').inputValue(), '');
  await page.locator('#dietFoodAmount').fill('0.5');
  assert.equal(await page.locator('#dietNutrCalories').inputValue(), '200');
  assert.equal(await page.locator('#dietNutrCopper').inputValue(), '0.0045');
  assert.equal(await page.locator('#dietNutrZinc').inputValue(), '0');
  await page.locator('#dietFoodUnit').selectOption('g');
  assert.equal(await page.locator('#dietForm').getAttribute('data-portion-missing'), 'true');
  await page.locator('#dietSubmit').click();
  assert.match(await page.locator('#dietEntryStatus').innerText(), /recipe uses servings/);
  assert.equal((await get()).foods.length, saved.foods.length);
  await page.locator('#dietFoodUnit').selectOption('serving');
  assert.equal(await page.locator('#dietForm').getAttribute('data-portion-missing'), 'false');
  assert.match(await page.locator('#dietEntryStatus').innerText(), /Recipe portion ready/);
  assert.equal(await page.locator('#dietNutrCalories').inputValue(), '200');
  await shot('gut-recipe-portion-card');
  await page.locator('#dietSubmit').click();
  assert.equal((await get()).foods.length, saved.foods.length + 1);
  const logged = (await get()).foods.at(-1);
  assert.equal(logged.recipeSnapshot.id, saved.mealRecipes[0].id);
  assert.equal(logged.nutritionSource.quality, 'estimate');
  assert.ok(logged.nutritionSource.incompleteNutrients.includes('iodine'));
  await page.locator('#closeDietModal').click();
  await page.locator('#gut-health-open').click();
  assert.match(await page.locator('#gut-observation-list').textContent(), /0.5 linked recipe serving/);
  await page.locator('#gut-recipe-status').scrollIntoViewIfNeeded();
  await shot('gut-recipe-observations');
  await page.locator('#gut-recipe-list button').filter({ hasText: 'Edit recipe' }).click();
  await form.locator('[name=yield]').fill('2');
  await form.locator('button[type=submit]').click();
  assert.equal((await get()).foods.at(-1).recipeSnapshot.yield, 1);
  await page.locator('#gut-observation-list button').filter({ hasText: 'Repeat as new period' }).click();
  assert.equal(await period.locator('[name=fastStart]').inputValue(), '');
  assert.equal(await period.locator('[name=fastEnd]').inputValue(), '');
  await period.locator('button[type=submit]').click();
  assert.equal((await get()).gutHealth.observations.length, 2);
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#gut-recipe-list button').filter({ hasText: 'Delete recipe' }).click();
  assert.equal((await get()).mealRecipes.length, 0);
  assert.equal((await get()).foods.at(-1).nutr.calories, 200);
  assert.match(await page.locator('#gut-observation-list').textContent(), /deleted template/);
  await page.locator('#gut-recipe-new').click();
  await form.locator('[name=recipeName]').fill('Synthetic ingredient recipe');
  const choices = page.locator('#gut-recipe-food option');
  const foodValue = await choices.filter({ hasText: 'Synthetic restore meal' }).getAttribute('value');
  await page.locator('#gut-recipe-food').selectOption(foodValue);
  await page.locator('#gut-recipe-copy-food').click();
  const copied = page.locator('.gut-recipe-ingredient').last();
  const before = Number(await copied.locator('[data-nutrient=calories]').inputValue());
  const amount = Number(await copied.locator('[data-field=amount]').inputValue());
  await copied.locator('[data-field=amount]').fill(String(amount / 2));
  assert.equal(Number(await copied.locator('[data-nutrient=calories]').inputValue()), before / 2);
  await page.locator('.gut-recipe-ingredient').first().getByRole('button', { name: 'Remove ingredient' }).click();
  await form.locator('button[type=submit]').click();
  assert.match(await page.locator('#gut-recipe-status').innerText(), /Recipe saved/);
  assert.equal((await get()).foods.length, saved.foods.length + 1);
  await page.locator('#gut-health-modal-close').click();
  await page.reload();
  await page.addStyleTag({ content: '*, *::before, *::after { animation: none !important; transition: none !important; }' });
  await page.locator('#gut-health-open').click();
  assert.match(await page.locator('#gut-recipe-list').innerText(), /Synthetic ingredient recipe/);
  assert.equal((await get()).gutHealth.observations.length, 2);
  await page.locator('#gut-recipe-list button').filter({ hasText: 'Review & log portion' }).click();
  assert.equal(Number(await page.locator('#dietNutrCalories').inputValue()), before / 2);
  await page.locator('#closeDietModal').click();
  await page.evaluate(value => {
    localStorage.setItem('fitnessTrackerData', value);
    window.dispatchEvent(new CustomEvent('bignuten:fitness-data-restored'));
  }, original);
  assert.equal((await get()).foods.length, JSON.parse(original).foods.length);
}
